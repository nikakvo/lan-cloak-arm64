#!/bin/sh
# mkhdr.sh <bpf.o> <out.h> - embed the "tc" section as struct bpf_insn[]
set -e
tmp=$(mktemp)
llvm-objcopy -O binary --only-section=tc "$1" "$tmp"
if llvm-readelf -r "$1" | grep -q R_BPF; then echo "relocations found - not supported" >&2; exit 1; fi
{
  echo "/* generated by mkhdr.sh from dhcp_clean.bpf.c - do not edit */"
  echo "static const unsigned char dhcp_clean_bytes[] __attribute__((aligned(8))) = {"
  od -An -v -tx1 "$tmp" | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g'
  echo "};"
  echo "#define dhcp_clean_insns (*(const struct bpf_insn (*)[sizeof(dhcp_clean_bytes) / 8])dhcp_clean_bytes)"
} > "$2"
rm -f "$tmp"
